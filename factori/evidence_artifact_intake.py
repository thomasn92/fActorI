def _proof_index_paths(root: Path, run_id: str) -> list[Path]:
    return sorted(
        path
        for path in (root / "runs" / run_id / "reports").glob(
            "proof-artifact-index-*.json"
        )
        if not path.name.endswith(".meta.json")
    )


def _experiment_index_paths(root: Path, run_id: str) -> list[Path]:
    return sorted(
        path
        for path in (root / "runs" / run_id / "reports").glob(
            "experiment-artifact-index-*.json"
        )
        if not path.name.endswith(".meta.json")
    )


def _next_evidence_reviewer_summary_id(root: Path, run_id: str) -> str:
    existing = sorted(
        path
        for path in (root / "runs" / run_id / "reports").glob(
            "reviewer-bundle-summary-after-evidence-artifacts-*.json"
        )
        if not path.name.endswith(".meta.json")
    )
    return f"reviewer-bundle-summary-after-evidence-artifacts-{len(existing) + 1:04d}"


def _proof_index_payload(
    *,
    run_id: str,
    root: Path,
    proofs: list[ProofArtifact],
    additional_paths: dict[str, str] | None = None,
) -> dict[str, Any]:
    paths = _artifact_paths_for_proofs(root, run_id, proofs, additional_paths)
    formal_passed = sum(1 for proof in proofs if _proof_is_verification_evidence(proof))
    informal = sum(1 for proof in proofs if proof.proof_type in _INFORMAL_PROOF_TYPES)
    return {
        "run_id": run_id,
        "proof_artifact_count": len(proofs),
        "formal_verification_passed_count": formal_passed,
        "informal_proof_artifact_count": informal,
        "proof_artifact_paths": paths,
        "publication_ready": False,
        "creates_scientific_validation": False,
        "implies_publication_readiness": False,
        "is_verification_evidence": False,
    }


def _experiment_index_payload(
    *,
    run_id: str,
    root: Path,
    experiments: list[ExperimentArtifact],
    additional_paths: dict[str, str] | None = None,
) -> dict[str, Any]:
    paths = _artifact_paths_for_experiments(root, run_id, experiments, additional_paths)
    completed = sum(1 for item in experiments if item.status == "completed")
    inconclusive = sum(1 for item in experiments if item.status == "inconclusive")
    failed = sum(
        1 for item in experiments if item.status in {"failed", "not_reproducible"}
    )
    return {
        "run_id": run_id,
        "experiment_artifact_count": len(experiments),
        "completed_experiment_count": completed,
        "inconclusive_experiment_count": inconclusive,
        "failed_experiment_count": failed,
        "experiment_artifact_paths": paths,
        "publication_ready": False,
        "creates_scientific_validation": False,
        "implies_publication_readiness": False,
        "is_verification_evidence": False,
    }


def _artifact_paths_for_proofs(
    root: Path,
    run_id: str,
    proofs: list[ProofArtifact],
    additional_paths: dict[str, str] | None = None,
) -> list[str]:
    result: list[str] = []
    for proof in proofs:
        if additional_paths and proof.proof_id in additional_paths:
            result.append(additional_paths[proof.proof_id])
            continue
        artifact_id = f"proof-artifact-{_safe_suffix(proof.proof_id)}"
        path = root / _report_path(run_id, artifact_id)
        if path.is_file():
            result.append(_report_path(run_id, artifact_id))
    return sorted(set(result))


def _artifact_paths_for_experiments(
    root: Path,
    run_id: str,
    experiments: list[ExperimentArtifact],
    additional_paths: dict[str, str] | None = None,
) -> list[str]:
    result: list[str] = []
    for experiment in experiments:
        if additional_paths and experiment.experiment_id in additional_paths:
            result.append(additional_paths[experiment.experiment_id])
            continue
        artifact_id = f"experiment-artifact-{_safe_suffix(experiment.experiment_id)}"
        path = root / _report_path(run_id, artifact_id)
        if path.is_file():
            result.append(_report_path(run_id, artifact_id))
    return sorted(set(result))


def _proof_is_verification_evidence(proof: ProofArtifact) -> bool:
    return proof.proof_type in _FORMAL_PROOF_TYPES and proof.checker_status == "passed"


def _artifact_metadata(
    *,
    stage: str,
    role: str,
    is_verification_evidence: bool,
) -> dict[str, Any]:
    return {
        "stage": stage,
        "artifact_role": role,
        "is_verification_evidence": is_verification_evidence,
        "creates_scientific_validation": False,
        "implies_publication_readiness": False,
    }


def _flatten_proof_text(proof: ProofArtifact) -> str:
    parts = [
        proof.proof_id,
        proof.proof_type,
        proof.statement,
        proof.artifact_path_optional or "",
        proof.checker_name_optional or "",
        proof.checker_version_optional or "",
        proof.checker_status,
        proof.review_status,
        proof.created_at,
        proof.ingested_at,
    ]
    parts.extend(proof.claim_ids_or_statement_ids)
    parts.extend(proof.limitations)
    return " ".join(parts).casefold()


def _flatten_experiment_text(experiment: ExperimentArtifact) -> str:
    parts = [
        experiment.experiment_id,
        experiment.experiment_type,
        experiment.hypothesis_or_question,
        experiment.status,
        experiment.dataset_name_optional or "",
        experiment.code_commit_hash_optional or "",
        experiment.command_optional or "",
        experiment.result_summary,
        experiment.created_at,
        experiment.ingested_at,
    ]
    parts.extend(experiment.claim_ids_or_section_ids)
    parts.extend(experiment.artifact_paths)
    parts.extend(experiment.limitations)
    parts.extend(str(value) for value in experiment.metrics.values())
    return " ".join(parts).casefold()


def _safe_suffix(value: str) -> str:
    return "".join(
        character if character.isalnum() else "-" for character in value
    ).strip("-")


def _contains_unsafe_phrase(text: str, phrase: str) -> bool:
    remainder = text
    for prefix in (
        "does not imply ",
        "does not establish ",
        "does not claim ",
        "cannot imply ",
        "cannot establish ",
        "cannot claim ",
        "is not ",
        "are not ",
        "without ",
        "no ",
    ):
        remainder = remainder.replace(f"{prefix}{phrase}", "")
    return phrase in remainder


def _report_path(run_id: str, artifact_id: str) -> str:
    return f"runs/{run_id}/reports/{artifact_id}.json"


def _require_run_path(root: Path, run_id: str) -> None:
    if not (root / "runs" / run_id).is_dir():
        raise EvidenceArtifactIntakeError(f"No run directory found for run_id={run_id}.")


