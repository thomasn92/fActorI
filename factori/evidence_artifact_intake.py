_FORMAL_PROOF_TYPES = {"lean_verified", "formal_verified", "external_certificate"}
_INFORMAL_PROOF_TYPES = {"informal_proof_note", "proof_plan"}
_FORBIDDEN_AUTHORITY_PHRASES = (
    "publication ready",
    "publication-ready",
    "ready for publication",
    "ready to submit",
    "approved for publication",
    "scientifically validated",
    "scientific validation is established",
    "novelty confirmed",
    "novelty validated",
    "correctness validated",
    "correctness is established",
    "paper is correct",
    "proves the paper",
    "validates the paper",
)
_PROOF_VERIFICATION_PHRASES = (
    "proof verified",
    "proof is verified",
    "formally verified",
    "formal verification passed",
)
_EXPERIMENT_VALIDATION_PHRASES = (
    "experiment validated",
    "experiment is validated",
    "empirically validated",
    "broad empirical validation",
    "exhaustive empirical validation",
)
_LLM_GENERATED_MARKERS = (
    "as an ai language model",
    "llm-generated",
    "generated by an llm",
    "generated by ai",
)


class EvidenceArtifactIntakeError(RuntimeError):
    """Raised when proof or experiment artifact intake is unsafe."""


@dataclass(frozen=True)
class ProofArtifactIngestResult:
    """Persisted proof artifact and refreshed reviewer summary."""

    run_id: str
    proof: ProofArtifact
    persistence: PersistenceResult
    proof_artifact: ArtifactRef
    proof_index_artifact: ArtifactRef
    reviewer_summary_artifact: ArtifactRef
    reviewer_summary_markdown_artifact: ArtifactRef


@dataclass(frozen=True)
class ExperimentArtifactIngestResult:
    """Persisted experiment artifact and refreshed reviewer summary."""

    run_id: str
    experiment: ExperimentArtifact
    persistence: PersistenceResult
    experiment_artifact: ArtifactRef
    experiment_index_artifact: ArtifactRef
    reviewer_summary_artifact: ArtifactRef
    reviewer_summary_markdown_artifact: ArtifactRef


def load_proof_artifact(proof_file: str | Path) -> ProofArtifact:
    """Load and structurally validate one local proof artifact JSON file."""
    path = Path(proof_file)
    try:
        return ProofArtifact.model_validate_json(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise EvidenceArtifactIntakeError(f"Unable to read proof file: {path}") from exc
    except ValidationError as exc:
        raise EvidenceArtifactIntakeError(f"Invalid proof artifact: {exc}") from exc


def load_experiment_artifact(experiment_file: str | Path) -> ExperimentArtifact:
    """Load and structurally validate one local experiment artifact JSON file."""
    path = Path(experiment_file)
    try:
        return ExperimentArtifact.model_validate_json(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise EvidenceArtifactIntakeError(
            f"Unable to read experiment file: {path}"
        ) from exc
    except ValidationError as exc:
        raise EvidenceArtifactIntakeError(f"Invalid experiment artifact: {exc}") from exc


def ingest_proof_artifact(
    *,
    run_id: str,
    root: str | Path,
    store: ArtifactStore,
    ledger: ResearchLedger,
    proof_file: str | Path,
) -> ProofArtifactIngestResult:
    """Validate and persist a local proof artifact without readiness upgrades."""
    root_path = Path(root)
    proof = load_proof_artifact(proof_file)
    _validate_proof_artifact(run_id=run_id, root=root_path, proof=proof)
    existing = _load_proof_artifacts(run_id=run_id, root=root_path)
    if any(item.proof_id == proof.proof_id for item in existing):
        raise EvidenceArtifactIntakeError(
            f"proof artifact already exists for proof_id={proof.proof_id}"
        )

    proof_artifact_id = f"proof-artifact-{_safe_suffix(proof.proof_id)}"
    proof_artifact_path = _report_path(run_id, proof_artifact_id)
    proof_index_id = f"proof-artifact-index-{len(_proof_index_paths(root_path, run_id)) + 1:04d}"
    reviewer_summary_id = _next_evidence_reviewer_summary_id(root_path, run_id)
    reviewer_summary = build_reviewer_bundle_summary(
        run_id=run_id,
        root=root_path,
        additional_proof_artifacts=[proof],
        additional_proof_artifact_paths=[proof_artifact_path],
    )
    reviewer_summary_markdown = render_reviewer_bundle_summary_markdown(
        reviewer_summary
    )
    metadata = _artifact_metadata(
        stage="proof_artifact_intake",
        role="proof_artifact_context",
        is_verification_evidence=_proof_is_verification_evidence(proof),
    )
    reviewer_metadata = _artifact_metadata(
        stage="proof_artifact_intake",
        role="reviewer_bundle_summary_context",
        is_verification_evidence=False,
    )
    index_payload = _proof_index_payload(
        run_id=run_id,
        root=root_path,
        proofs=[*existing, proof],
        additional_paths={proof.proof_id: proof_artifact_path},
    )
    persistence = persist_artifacts_with_commit(
        run_id=run_id,
        store=store,
        ledger=ledger,
        artifact_specs=[
            ArtifactWriteSpec(
                proof_artifact_id,
                ArtifactType.REPORT,
                proof,
                "json",
                metadata,
            ),
            ArtifactWriteSpec(
                proof_index_id,
                ArtifactType.REPORT,
                index_payload,
                "json",
                _artifact_metadata(
                    stage="proof_artifact_intake",
                    role="proof_artifact_index_context",
                    is_verification_evidence=False,
                ),
            ),
            ArtifactWriteSpec(
                reviewer_summary_id,
                ArtifactType.REPORT,
                reviewer_summary,
                "json",
                reviewer_metadata,
            ),
            ArtifactWriteSpec(
                f"{reviewer_summary_id}-markdown",
                ArtifactType.REPORT,
                reviewer_summary_markdown,
                "markdown",
                reviewer_metadata,
                filename_stem=reviewer_summary_id,
            ),
        ],
        action_type=ControllerActionType.PROOF_ARTIFACT_INGESTED,
        commit_payload={
            "run_id": run_id,
            "proof_id": proof.proof_id,
            "proof_type": proof.proof_type,
            "checker_status": proof.checker_status,
            "is_verification_evidence": _proof_is_verification_evidence(proof),
            "formal_verification_passed": _proof_is_verification_evidence(proof),
            "publication_ready": False,
            "creates_scientific_validation": False,
            "implies_publication_readiness": False,
            "reviewer_summary_updated": True,
        },
    )
    by_id = {artifact.id: artifact for artifact in persistence.artifacts}
    return ProofArtifactIngestResult(
        run_id=run_id,
        proof=proof,
        persistence=persistence,
        proof_artifact=by_id[proof_artifact_id],
        proof_index_artifact=by_id[proof_index_id],
        reviewer_summary_artifact=by_id[reviewer_summary_id],
        reviewer_summary_markdown_artifact=by_id[f"{reviewer_summary_id}-markdown"],
    )


